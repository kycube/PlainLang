#!/usr/bin/env python3
"""Regenerate skills/plainlang/references/{rules,principles,examples}.md from the JSON data.

Run after editing anything in skills/plainlang/data/. CI fails if the generated files are stale.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "plainlang"
DATA = SKILL / "data"
REFS = SKILL / "references"
HEADER = "<!-- Generated by tools/build_docs.py from skills/plainlang/data. Do not edit by hand. -->\n\n"


def rules_md(meta: dict, rules: list[dict]) -> str:
    out = [HEADER, "# PlainLang rules\n\n",
           "Each rule says what not to write and what to write instead. `pattern` rules are checked by "
           "`scripts/plainlang.py`; `judgment` rules need a reviewer. Severity `error` means fix it; `warn` means "
           "check it and use judgment.\n\n"]
    for cat in meta["categories"]:
        group = [r for r in rules if r["category"] == cat["id"]]
        if not group:
            continue
        out.append(f"## {cat['name']}\n\n")
        for r in group:
            kind = "pattern" if (r.get("patterns") or r.get("substitutions")) else "judgment"
            out.append(f"### {r['id']} {r['name']}\n\n")
            out.append(f"*{r['severity']}, {kind}*\n\n")
            out.append(f"- **Don't:** {r['dont']}\n- **Do:** {r['do']}\n- **Why:** {r['rationale']}\n")
            if r.get("exceptions"):
                out.append(f"- **Exceptions:** {r['exceptions']}\n")
            if r.get("detect"):
                out.append("- **Look for:** " + "; ".join(r["detect"]) + "\n")
            exs = r.get("examples", [])[:3]
            if exs:
                out.append("\n| Don't write | Write instead |\n|---|---|\n")
                for e in exs:
                    bad = e["bad"].replace("|", "\\|").replace("\n", "<br>")
                    good = e["better"].replace("|", "\\|").replace("\n", "<br>")
                    out.append(f"| {bad} | {good} |\n")
            if r.get("substitutions"):
                out.append(f"\nSubstitution list: {len(r['substitutions'])} entries in `data/rules.json` (`{r['id']}`).\n")
            out.append(f"\nSources: {r.get('source', '')}\n\n")
    return "".join(out)


def principles_md(ps: list[dict]) -> str:
    out = [HEADER, "# PlainLang principles\n\nWhy the rules exist, with the evidence behind them.\n\n"]
    for p in ps:
        out.append(f"## {p['id']} {p['title']}\n\n{p['summary']}\n\n")
        for g in p.get("guidance", []):
            out.append(f"- {g}\n")
        if p.get("evidence"):
            out.append(f"\n**Evidence:** {p['evidence']}\n")
        if p.get("caveats"):
            out.append(f"\n**Caveat:** {p['caveats']}\n")
        if p.get("rule_ids"):
            out.append(f"\n**Rules:** {', '.join(p['rule_ids'])}\n")
        srcs = "; ".join(f"[{s['name']}]({s['url']})" if s.get("url") else s["name"] for s in p.get("sources", []))
        out.append(f"\n**Sources:** {srcs}\n\n")
    return "".join(out)


def examples_md(xs: list[dict]) -> str:
    out = [HEADER, "# Human-identified examples\n\n",
           "Writing that people (editors, award juries, style-guide authors, researchers) singled out as good or bad. "
           "Entries marked *described* paraphrase a text too long or too restricted to quote.\n\n"]
    for x in xs:
        tag = {"bad": "Bad", "good": "Good", "pair": "Before / after"}.get(x["kind"], x["kind"])
        out.append(f"## {x['id']} {tag}: {x['identified_by']}{' (' + x['year'] + ')' if x.get('year') else ''}\n\n")
        if x.get("text"):
            out.append(f"- **{'Text' if x['kind'] == 'good' else 'Before'}:** {x['text']}{'' if x.get('verbatim', True) else ' *(described)*'}\n")
        if x.get("rewrite"):
            out.append(f"- **After:** {x['rewrite']}\n")
        out.append(f"- **Why:** {x['why']}\n- **Rules:** {', '.join(x.get('rule_ids', []))}\n")
        if x.get("source_url"):
            out.append(f"- **Source:** {x['source_url']}\n")
        out.append("\n")
    return "".join(out)


def build() -> dict[Path, str]:
    data = json.loads((DATA / "rules.json").read_text(encoding="utf-8"))
    ps = json.loads((DATA / "principles.json").read_text(encoding="utf-8"))
    xs = json.loads((DATA / "exemplars.json").read_text(encoding="utf-8"))
    return {
        REFS / "rules.md": rules_md(data["meta"], data["rules"]),
        REFS / "principles.md": principles_md(ps),
        REFS / "examples.md": examples_md(xs),
    }


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, content in build().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale generated files (run tools/build_docs.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
